/* ===== ТЕКУЩИЙ ВАРИАНТ (С ВРАЩЕНИЕМ) ===== */

// Получаем ссылку на элемент <canvas> из HTML по его id="canvas"
let canvas = document.getElementById("canvas");
// Получаем 2D-контекст для рисования
let context = canvas.getContext("2d");
// Создаём объект изображения
let image = new Image();
// Запускаем загрузку картинки
image.src = "img/ball.png";

// x, y — координаты верхнего левого угла мяча (стартуем в левом верхнем углу)
let x = 0, y = 0;
// direction — направление движения по горизонтали: 1 = вправо, -1 = влево
let direction = 1;
// angle — текущий угол поворота мяча в радианах
let angle = 0;
// directionAngle — шаг поворота за один кадр (величина и знак = направление вращения)
let directionAngle = 0.05;

// Запускаем цикл анимации: функция вызывается каждые 10 мс
setInterval(() => {
    // Стираем ВЕСЬ холст (иначе повёрнутый мяч оставит «хвосты» от прошлых кадров)
    context.clearRect(0, 0, canvas.width, canvas.height);
    // Сдвигаем мяч на 1 пиксель в текущем направлении
    x += direction;
    // Если правый край мяча достиг правой границы — разворот влево + смена вращения
    if (x + 100 >= canvas.clientWidth) {
        direction = -1;
        directionAngle = -directionAngle; // вращение теперь в обратную сторону
    }

    // Если мяч достиг левой границы — разворот вправо + смена направления вращения
    if (x <= 0) {
        direction = 1;
        directionAngle = -directionAngle; // вращение теперь в обратную сторону
    }

    // Сохраняем текущее состояние контекста (координаты, повороты) в стек
    context.save();
    // Переносим начало координат в ЦЕНТР мяча (x+50, y+50), чтобы вращать вокруг центра
    context.translate(x + 50, y + 50);
    // Поворачиваем систему координат на текущий угол angle
    context.rotate(angle);
    // Рисуем мяч так, чтобы его центр совпал с новым началом координат (-50,-50)
    context.drawImage(image, -50, -50, 100, 100);
    // Восстанавливаем состояние контекста — отменяем translate и rotate
    context.restore();

    // Увеличиваем угол поворота на величину directionAngle (знак задаёт направление вращения)
    angle += directionAngle;
}, 10); 
